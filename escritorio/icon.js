const ResEdit=require('resedit'); const PE=require('pe-library'); const fs=require('fs');
const exePath=process.argv[2], ico=process.argv[3], ver=process.argv[4];
const exe=PE.NtExecutable.from(fs.readFileSync(exePath),{ignoreCert:true});
const res=PE.NtExecutableResource.from(exe);
const iconFile=ResEdit.Data.IconFile.from(fs.readFileSync(ico));
const groups=ResEdit.Resource.IconGroupEntry.fromEntries(res.entries);
const gid = groups.length? groups[0].id : 1; const lang = groups.length? groups[0].lang : 1033;
ResEdit.Resource.IconGroupEntry.replaceIconsForResource(res.entries,gid,lang,iconFile.icons.map(i=>i.data));
const vi=ResEdit.Resource.VersionInfo.fromEntries(res.entries)[0];
const [a,b,c]=ver.split('.').map(Number);
vi.setFileVersion(a,b,c,0,1033); vi.setProductVersion(a,b,c,0,1033);
vi.setStringValues({lang:1033,codepage:1200},{FileDescription:'Cierre Cignetti',ProductName:'Cierre Cignetti',CompanyName:'Mateo Gutiérrez',OriginalFilename:'Cierre Cignetti.exe',InternalName:'Cierre Cignetti',LegalCopyright:'Mateo Gutiérrez'});
vi.outputToResourceEntries(res.entries);
res.outputResource(exe); fs.writeFileSync(exePath, Buffer.from(exe.generate()));
console.log('icon ok');
